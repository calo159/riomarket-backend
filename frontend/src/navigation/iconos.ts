import {
  BadgeCheck,
  BarChart3,
  Bell,
  BookOpenCheck,
  Circle,
  ClipboardList,
  CreditCard,
  KeyRound,
  LayoutDashboard,
  LayoutList,
  LogIn,
  MapPin,
  Package,
  Percent,
  ShieldCheck,
  ShoppingBag,
  ShoppingCart,
  Star,
  Store,
  Tags,
  Ticket,
  User,
  Users,
  type LucideIcon,
} from 'lucide-react';

const ICONOS: Record<string, LucideIcon> = {
  BadgeCheck,
  BarChart3,
  Bell,
  BookOpenCheck,
  ClipboardList,
  CreditCard,
  KeyRound,
  LayoutDashboard,
  LayoutList,
  LogIn,
  MapPin,
  Package,
  Percent,
  ShieldCheck,
  ShoppingBag,
  ShoppingCart,
  Star,
  Store,
  Tags,
  Ticket,
  User,
  Users,
};

export function iconoDe(nombre: string | null | undefined): LucideIcon {
  return (nombre && ICONOS[nombre]) || Circle;
}
